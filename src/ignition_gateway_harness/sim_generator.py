"""Peripheral Simulation Generator for Ignition Gateway Fleet.

Generates Docker Compose stacks and helper artifacts to simulate production OT/IT
ecosystems around the Ignition fleet without modifying the gateway backups:
- PostgreSQL / TimescaleDB pre-populated with discovered databases, users, and historian tables
- Mailpit SMTP container for alarm notifications
- Mosquitto MQTT broker for Sparkplug B and Cirrus Link modules
- Mock OPC-UA & Rockwell CIP / PLC socket responder
- Network aliases matching all discovered production hostnames
"""

import os
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple
import yaml

from ignition_gateway_harness.backup_analyzer import FleetAnalysisReport
from ignition_gateway_harness.compose_builder import CleanYamlDumper, format_relative_path
