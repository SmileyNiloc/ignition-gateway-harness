def generate_init_sql(report: FleetAnalysisReport, db_type: str = "mssql") -> str:
    """Generate SQL initialization script for Microsoft SQL Server 2022 (default) or other supported DBs based on discovered backups."""
    # Discovered databases
    databases: Set[str] = set()
    for db_set in report.database_targets.values():
        databases.update(db_set)

    # Standard fallback databases if none discovered
    default_dbs = {"prod", "mes", "scada", "scada_head", "mes_old", "scada_tagio1", "scada_tagio2", "ignition"}
    databases.update(default_dbs)

    # Discovered users
    users: Set[str] = set()
    for ga in report.gateways.values():
        for db in ga.databases:
            if db.username:
                users.add(db.username.strip())

    if not users:
        users = {"ignition", "defsvcmesdev", "defsvcscadadev", "defsvcprdheadprd"}
    else:
        users.add("ignition")

    if db_type == "mssql":
        sql_lines = [
            "-- Auto-generated by Ignition Gateway Harness Peripheral Simulator",
            "-- Target Database: Microsoft SQL Server 2022",
            "-- Source of truth: Discovered databases and users from gateway backups",
            "USE [master];",
            "GO",
            "",
            "-- 1. Create Discovered Databases with Case-Insensitive Collation",
        ]
        for db_name in sorted(databases):
            clean_db = db_name.lower().replace("-", "_").strip()
            if clean_db and clean_db not in ("master", "tempdb", "model", "msdb"):
                sql_lines.extend([
                    f"IF NOT EXISTS (SELECT name FROM sys.databases WHERE name = N'{clean_db}')",
                    "BEGIN",
                    f"    PRINT 'Creating database [{clean_db}] with collation SQL_Latin1_General_CP1_CI_AS...';",
                    f"    CREATE DATABASE [{clean_db}] COLLATE SQL_Latin1_General_CP1_CI_AS;",
                    f"    ALTER DATABASE [{clean_db}] SET RECOVERY SIMPLE;",
                    "END",
                    "GO",
                    "",
                ])

        sql_lines.extend([
            "-- 2. Configure sa and Application Logins with password",
            "ALTER LOGIN [sa] WITH PASSWORD = N'password', CHECK_POLICY = OFF;",
            "GO",
            "",
        ])
        for u in sorted(users):
            clean_u = u.strip()
            if clean_u and clean_u.lower() not in ("sa", "dbo"):
                sql_lines.extend([
                    f"IF NOT EXISTS (SELECT name FROM sys.server_principals WHERE name = N'{clean_u}')",
                    "BEGIN",
                    f"    PRINT 'Creating server login [{clean_u}]...';",
                    f"    CREATE LOGIN [{clean_u}] WITH PASSWORD = N'password',",
                    "        DEFAULT_DATABASE = [master],",
                    "        CHECK_EXPIRATION = OFF,",
                    "        CHECK_POLICY = OFF;",
                    "END",
                    "ELSE",
                    "BEGIN",
                    f"    ALTER LOGIN [{clean_u}] WITH PASSWORD = N'password',",
                    "        CHECK_EXPIRATION = OFF,",
                    "        CHECK_POLICY = OFF;",
                    "END",
                    "GO",
                    "",
                ])

        sql_lines.extend([
            "-- 3. Map Users and Grant db_owner Privileges Across Discovered Databases",
        ])
        for db_name in sorted(databases):
            clean_db = db_name.lower().replace("-", "_").strip()
            if clean_db and clean_db not in ("master", "tempdb", "model", "msdb"):
                sql_lines.extend([
                    f"USE [{clean_db}];",
                    "GO",
                ])
                for u in sorted(users):
                    clean_u = u.strip()
                    if clean_u and clean_u.lower() not in ("sa", "dbo"):
                        sql_lines.extend([
                            f"IF NOT EXISTS (SELECT name FROM sys.database_principals WHERE name = N'{clean_u}')",
                            "BEGIN",
                            f"    CREATE USER [{clean_u}] FOR LOGIN [{clean_u}];",
                            "END",
                            f"ALTER ROLE [db_owner] ADD MEMBER [{clean_u}];",
                            "GO",
                        ])
                sql_lines.append("")

        sql_lines.extend([
            "-- 4. Standard Ignition Historian, Alarm Journal, and Audit Tables",
        ])
        for db_name in sorted(databases):
            clean_db = db_name.lower().replace("-", "_").strip()
            if clean_db and clean_db not in ("master", "tempdb", "model", "msdb"):
                sql_lines.extend([
                    f"USE [{clean_db}];",
                    "GO",
                    "",
                    "IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = N'sqlth_drv')",
                    "BEGIN",
                    "    CREATE TABLE [dbo].[sqlth_drv] (",
                    "        [id] INT IDENTITY(1,1) PRIMARY KEY,",
                    "        [name] VARCHAR(255) NOT NULL UNIQUE",
                    "    );",
                    "    INSERT INTO [dbo].[sqlth_drv] ([name]) VALUES ('default');",
                    "END",
                    "GO",
                    "",
                    "IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = N'sqlth_tables')",
                    "BEGIN",
                    "    CREATE TABLE [dbo].[sqlth_tables] (",
                    "        [id] INT IDENTITY(1,1) PRIMARY KEY,",
                    "        [tablename] VARCHAR(255) NOT NULL UNIQUE,",
                    "        [drvid] INT FOREIGN KEY REFERENCES [dbo].[sqlth_drv]([id])",
                    "    );",
                    "END",
                    "GO",
                    "",
                    "IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = N'sqlth_te')",
                    "BEGIN",
                    "    CREATE TABLE [dbo].[sqlth_te] (",
                    "        [id] INT IDENTITY(1,1) PRIMARY KEY,",
                    "        [tagid] VARCHAR(500) NOT NULL UNIQUE,",
                    "        [datatype] INT NOT NULL,",
                    "        [querymode] INT NOT NULL",
                    "    );",
                    "END",
                    "GO",
                    "",
                    "IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = N'sqlth_sce')",
                    "BEGIN",
                    "    CREATE TABLE [dbo].[sqlth_sce] (",
                    "        [id] INT IDENTITY(1,1) PRIMARY KEY,",
                    "        [scid] INT NOT NULL,",
                    "        [start_time] BIGINT NOT NULL,",
                    "        [end_time] BIGINT NULL",
                    "    );",
                    "END",
                    "GO",
                    "",
                    "IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = N'alarm_events')",
                    "BEGIN",
                    "    CREATE TABLE [dbo].[alarm_events] (",
                    "        [id] INT IDENTITY(1,1) PRIMARY KEY,",
                    "        [eventid] VARCHAR(255) NOT NULL,",
                    "        [source] VARCHAR(1000) NOT NULL,",
                    "        [displaypath] VARCHAR(1000) NULL,",
                    "        [priority] INT NULL,",
                    "        [eventtime] DATETIME NULL,",
                    "        [eventflags] INT NULL",
                    "    );",
                    "END",
                    "GO",
                    "",
                    "IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = N'alarm_event_data')",
                    "BEGIN",
                    "    CREATE TABLE [dbo].[alarm_event_data] (",
                    "        [id] INT IDENTITY(1,1) PRIMARY KEY,",
                    "        [eventid] VARCHAR(255) NOT NULL,",
                    "        [propname] VARCHAR(255) NOT NULL,",
                    "        [propval_str] NVARCHAR(MAX) NULL,",
                    "        [propval_int] BIGINT NULL,",
                    "        [propval_float] FLOAT NULL",
                    "    );",
                    "END",
                    "GO",
                    "",
                    "IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = N'audit_events')",
                    "BEGIN",
                    "    CREATE TABLE [dbo].[audit_events] (",
                    "        [audit_events_id] INT IDENTITY(1,1) PRIMARY KEY,",
                    "        [event_timestamp] DATETIME NOT NULL DEFAULT GETDATE(),",
                    "        [actor] NVARCHAR(255) NOT NULL,",
                    "        [actor_host] NVARCHAR(255) NULL,",
                    "        [action] NVARCHAR(255) NOT NULL,",
                    "        [action_target] NVARCHAR(255) NULL,",
                    "        [action_value] NVARCHAR(MAX) NULL,",
                    "        [status_code] INT NOT NULL DEFAULT 0",
                    "    );",
                    "END",
                    "GO",
                    "",
                    "IF NOT EXISTS (SELECT * FROM sys.objects WHERE name = N'AUDIT_EVENTS')",
                    "BEGIN",
                    "    CREATE SYNONYM [dbo].[AUDIT_EVENTS] FOR [dbo].[audit_events];",
                    "END",
                    "GO",
                    "",
                ])

        return "\n".join(sql_lines)

    elif db_type == "mysql":
        sql_lines = [
            "-- Auto-generated by Ignition Gateway Harness Peripheral Simulator",
            "-- Target Database: MySQL 8.0",
            "",
        ]
        for db_name in sorted(databases):
            clean_db = db_name.lower().replace("-", "_").strip()
            if clean_db and clean_db not in ("mysql", "information_schema", "performance_schema", "sys"):
                sql_lines.append(f"CREATE DATABASE IF NOT EXISTS `{clean_db}`;")
        for u in sorted(users):
            clean_u = u.strip()
            if clean_u and clean_u.lower() not in ("root",):
                sql_lines.append(f"CREATE USER IF NOT EXISTS '{clean_u}'@'%' IDENTIFIED BY 'password';")
                sql_lines.append(f"ALTER USER '{clean_u}'@'%' IDENTIFIED BY 'password';")
                for db_name in sorted(databases):
                    clean_db = db_name.lower().replace("-", "_").strip()
                    if clean_db and clean_db not in ("mysql", "information_schema", "performance_schema", "sys"):
                        sql_lines.append(f"GRANT ALL PRIVILEGES ON `{clean_db}`.* TO '{clean_u}'@'%';")
        sql_lines.extend([
            "FLUSH PRIVILEGES;",
            "USE `prod`;",
            "CREATE TABLE IF NOT EXISTS `sqlth_drv` (`id` INT AUTO_INCREMENT PRIMARY KEY, `name` VARCHAR(255) NOT NULL UNIQUE);",
            "INSERT IGNORE INTO `sqlth_drv` (`name`) VALUES ('default');",
            "CREATE TABLE IF NOT EXISTS `sqlth_tables` (`id` INT AUTO_INCREMENT PRIMARY KEY, `tablename` VARCHAR(255) NOT NULL UNIQUE, `drvid` INT, FOREIGN KEY (`drvid`) REFERENCES `sqlth_drv`(`id`));",
            "CREATE TABLE IF NOT EXISTS `sqlth_te` (`id` INT AUTO_INCREMENT PRIMARY KEY, `tagid` VARCHAR(500) NOT NULL UNIQUE, `datatype` INT NOT NULL, `querymode` INT NOT NULL);",
            "CREATE TABLE IF NOT EXISTS `sqlth_sce` (`id` INT AUTO_INCREMENT PRIMARY KEY, `scid` INT NOT NULL, `start_time` BIGINT NOT NULL, `end_time` BIGINT NULL);",
            "CREATE TABLE IF NOT EXISTS `alarm_events` (`id` INT AUTO_INCREMENT PRIMARY KEY, `eventid` VARCHAR(255) NOT NULL, `source` VARCHAR(1000) NOT NULL, `displaypath` VARCHAR(1000), `priority` INT, `eventtime` DATETIME, `eventflags` INT);",
            "CREATE TABLE IF NOT EXISTS `alarm_event_data` (`id` INT AUTO_INCREMENT PRIMARY KEY, `eventid` VARCHAR(255) NOT NULL, `propname` VARCHAR(255) NOT NULL, `propval_str` TEXT, `propval_int` BIGINT, `propval_float` DOUBLE);",
            "CREATE TABLE IF NOT EXISTS `audit_events` (`audit_events_id` INT AUTO_INCREMENT PRIMARY KEY, `event_timestamp` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, `actor` VARCHAR(255) NOT NULL, `actor_host` VARCHAR(255) NULL, `action` VARCHAR(255) NOT NULL, `action_target` VARCHAR(255) NULL, `action_value` LONGTEXT NULL, `status_code` INT NOT NULL DEFAULT 0);",
        ])
        return "\n".join(sql_lines)

    else:
        # Fallback to PostgreSQL / TimescaleDB
        sql_lines = [
            "-- Auto-generated by Ignition Gateway Harness Peripheral Simulator",
            "-- Source of truth: Discovered databases and users from gateway backups",
            "",
        ]
        for db_name in sorted(databases):
            clean_db = db_name.lower().replace("-", "_").strip()
            if clean_db and clean_db != "postgres" and clean_db != "template1":
                sql_lines.append(f"SELECT 'CREATE DATABASE {clean_db}' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '{clean_db}')\\gexec")

        user_list = [u.strip() for u in sorted(users) if u.strip() and u.strip().lower() not in ("postgres",)]
        user_list_sql = ", ".join(f"'{u}'" for u in user_list)
        if user_list_sql:
            sql_lines.extend([
                "",
                "-- Discovered user accounts with full privileges across simulated databases",
                "DO $$",
                "DECLARE",
                "    u text;",
                "BEGIN",
                f"    FOR u IN (SELECT unnest(ARRAY[{user_list_sql}]))",
                "    LOOP",
                "        IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = u) THEN",
                "            EXECUTE format('CREATE USER %I WITH PASSWORD %L SUPERUSER CREATEDB', u, 'password');",
                "        END IF;",
                "    END LOOP;",
                "END $$;",
            ])
        sql_lines.extend([
            "",
            "-- Standard Ignition Historian and Alarm Journal tables in default ignition DB",
            "\\c ignition;",
            "",
            "CREATE TABLE IF NOT EXISTS sqlth_drv (",
            "    id SERIAL PRIMARY KEY,",
            "    name VARCHAR(255) NOT NULL UNIQUE",
            ");",
            "INSERT INTO sqlth_drv (name) VALUES ('default') ON CONFLICT DO NOTHING;",
            "",
            "CREATE TABLE IF NOT EXISTS sqlth_tables (",
            "    id SERIAL PRIMARY KEY,",
            "    tablename VARCHAR(255) NOT NULL UNIQUE,",
            "    drvid INT REFERENCES sqlth_drv(id)",
            ");",
            "",
            "CREATE TABLE IF NOT EXISTS sqlth_te (",
            "    id SERIAL PRIMARY KEY,",
            "    tagid VARCHAR(500) NOT NULL UNIQUE,",
            "    datatype INT NOT NULL,",
            "    querymode INT NOT NULL",
            ");",
            "",
            "CREATE TABLE IF NOT EXISTS sqlth_sce (",
            "    id SERIAL PRIMARY KEY,",
            "    scid INT NOT NULL,",
            "    start_time BIGINT NOT NULL,",
            "    end_time BIGINT",
            ");",
            "",
            "CREATE TABLE IF NOT EXISTS alarm_events (",
            "    id SERIAL PRIMARY KEY,",
            "    eventid VARCHAR(255) NOT NULL,",
            "    source VARCHAR(1000) NOT NULL,",
            "    displaypath VARCHAR(1000),",
            "    priority INT,",
            "    eventtime TIMESTAMP,",
            "    eventflags INT",
            ");",
            "",
            "CREATE TABLE IF NOT EXISTS alarm_event_data (",
            "    id SERIAL PRIMARY KEY,",
            "    eventid VARCHAR(255) NOT NULL,",
            "    propname VARCHAR(255) NOT NULL,",
            "    propval_str TEXT,",
            "    propval_int BIGINT,",
            "    propval_float DOUBLE PRECISION",
            ");",
            "",
            "CREATE TABLE IF NOT EXISTS audit_events (",
            "    audit_events_id SERIAL PRIMARY KEY,",
            "    event_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,",
            "    actor VARCHAR(255) NOT NULL,",
            "    actor_host VARCHAR(255),",
            "    action VARCHAR(255) NOT NULL,",
            "    action_target VARCHAR(255),",
            "    action_value TEXT,",
            "    status_code INT NOT NULL DEFAULT 0",
            ");",
            "",
        ])
        return "\n".join(sql_lines)


